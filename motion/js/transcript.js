    // Markdown-lite, matching what the film's renderer supported: **bold**,
    // bullet lines, numbered steps, blank-line paragraphs. Deliberately not a
    // markdown library — nine strings don't justify a dependency, and an
    // unrecognised syntax showing as literal asterisks is a better failure
    // than one that renders as markup.
    function escapeHtml(s) {
        return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    }

    function inline(s) {
        return escapeHtml(s).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
    }

    function render(text) {
        var out = '';
        var list = null;   // 'ul' | 'ol' | null

        function closeList() {
            if (list) { out += '</' + list + '>'; list = null; }
        }

        text.split('\n').forEach(function (raw) {
            var line = raw.trim();
            if (!line) { closeList(); return; }

            if (/^•\s+/.test(line)) {
                if (list !== 'ul') { closeList(); out += '<ul class="ts-list">'; list = 'ul'; }
                out += '<li>' + inline(line.replace(/^•\s+/, '')) + '</li>';
                return;
            }

            if (/^\d+\.\s+/.test(line)) {
                if (list !== 'ol') { closeList(); out += '<ol class="ts-steps">'; list = 'ol'; }
                out += '<li>' + inline(line.replace(/^\d+\.\s+/, '')) + '</li>';
                return;
            }

            closeList();
            // A line that is nothing but bold is a heading in this content —
            // "**Maya · OES Classroom**" — and reads as one.
            if (/^\*\*[^*]+\*\*$/.test(line)) {
                out += '<p class="ts-head">' + inline(line) + '</p>';
            } else {
                out += '<p>' + inline(line) + '</p>';
            }
        });

        closeList();
        return out;
    }

    function initTranscript() {
        var root = document.querySelector('[data-transcript]');
        if (!root) return;

        var open = null;

        SESSION.forEach(function (entry, i) {
            var id = 'ts-answer-' + i;

            var q = document.createElement('button');
            q.type = 'button';
            q.className = 'ts-q';
            q.setAttribute('aria-expanded', 'false');
            q.setAttribute('aria-controls', id);
            q.innerHTML = '<span class="ts-q-text">' + escapeHtml(entry.q) + '</span>' +
                '<span class="ts-q-meta">' + entry.lines + ' lines</span>';

            var card = document.createElement('div');
            card.className = 'ts-a-card';
            card.innerHTML = render(entry.a);

            var inner = document.createElement('div');
            inner.className = 'ts-a-inner';
            inner.appendChild(card);

            var panel = document.createElement('div');
            panel.className = 'ts-a';
            panel.id = id;
            panel.appendChild(inner);

            var turn = document.createElement('li');
            turn.className = 'ts-turn';
            turn.appendChild(q);
            turn.appendChild(panel);
            root.appendChild(turn);
        });

        // One at a time: an open answer runs to a thousand pixels, and two of
        // them means the next question is two screens from the last.
        //
        // Which creates the jump this guards against. Close a long answer that
        // sits ABOVE the question you just tapped and everything below it
        // slides up by that much — you tap a question and the page throws you
        // somewhere else. So the outgoing panel closes instantly rather than
        // over 520ms, and the scroll position is corrected by exactly the
        // height it gave up, in the same frame. The question you tapped does
        // not move at all.
        function setOpen(turn, anchor) {
            if (open && open !== turn) {
                var before = anchor ? anchor.getBoundingClientRect().top : 0;
                var closing = open;

                closing.classList.add('is-instant');
                closing.classList.remove('is-open');
                closing.querySelector('.ts-q').setAttribute('aria-expanded', 'false');

                if (anchor) {
                    // Reading the rect forces the layout, so the collapse has
                    // already happened by the time this is measured.
                    var after = anchor.getBoundingClientRect().top;
                    if (after !== before) window.scrollBy(0, after - before);
                }

                requestAnimationFrame(function () {
                    closing.classList.remove('is-instant');
                });
            }
            open = turn;
        }

        root.addEventListener('click', function (e) {
            var q = e.target.closest('.ts-q');
            if (!q) return;

            var turn = q.parentElement;
            var wasOpen = turn.classList.contains('is-open');
            setOpen(wasOpen ? null : turn, q);
            turn.classList.toggle('is-open', !wasOpen);
            q.setAttribute('aria-expanded', wasOpen ? 'false' : 'true');
        });

        // The first answer is open on arrival — nine collapsed questions is a
        // menu, and the claim this section makes is that the answers are real,
        // which nobody can see until one is on screen.
        //
        // Except on a phone, where that same answer is 1,700px: you would have
        // to scroll a wall of text to discover there were eight more questions.
        // There the nine questions ARE the opening view, each already labelled
        // with how long its answer runs, and the reader picks one.
        var narrow = window.matchMedia('(max-width: 640px)').matches;
        var first = root.firstElementChild;
        if (first && !narrow) {
            first.classList.add('is-open');
            first.querySelector('.ts-q').setAttribute('aria-expanded', 'true');
            open = first;
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initTranscript);
    } else {
        initTranscript();
    }
